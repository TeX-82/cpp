#include "tex_pool.h"

#include <map>

static auto make_s_to_i()
{
	std::map<std::string_view, uint64_t> retval;

	uint64_t n = 256; // first 256 are setup in a special way by tex.web
	for (const auto& s : tex_pool())
	{
		retval[s] = n;
		n++;
	}
	return retval;
}

std::optional<uint64_t> string_number(const std::string_view& s)
{
	static const std::map<std::string_view, uint64_t> s_to_i = make_s_to_i();
	const auto it = s_to_i.find(s);
	if (it != s_to_i.end())
	{
		return it->second;
	}

	return std::optional<uint64_t>();
}

